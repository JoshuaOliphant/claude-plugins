#!/usr/bin/env python3
# ABOUTME: Generate `claude plugin eval` trigger cases from the evals/*-eval.json fixtures.
# ABOUTME: Turns the static should_trigger datasets into runnable cases under each plugin.
"""Generate plugin-eval trigger cases from the ``evals/*-eval.json`` fixtures.

The fixtures under ``evals/`` are lists of ``{"query": ..., "should_trigger": bool}``.
On their own nothing executes them. This script compiles each fixture into real
``claude plugin eval`` cases under the owning plugin's ``evals/`` directory:

    plugins/<plugin>/evals/<fixture>-<pos|neg>-<NN>/
        prompt.md            # frontmatter + the fixture's query verbatim
        graders/trigger.md   # trace regex pinned to this fixture's skill

Each grader is a regex over the run trace pinned to the plugin-qualified skill id
the Skill tool records, so a case is exact even inside a multi-skill plugin:
compound-capture firing does not satisfy a compound-retrieve case. Graders are free
to score -- no LLM judge is billed -- but each case still costs one agent run per
arm, so the suites are sampled rather than exhaustive (see ``--limit``).

Run the generated suites with ``--ablation none``: a skill cannot fire without its
plugin loaded, so the no-plugin baseline arm is a foregone conclusion and only
doubles the bill.

Usage:
    python scripts/gen_trigger_evals.py --check          # fail if generated cases are stale
    python scripts/gen_trigger_evals.py --write          # (re)generate, 3 per polarity
    python scripts/gen_trigger_evals.py --write --limit 5
    python scripts/gen_trigger_evals.py --write --fixture mochi-creator-eval
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURES = REPO_ROOT / "evals"

# Which (plugin, skill) each fixture is asserting about. The skill name is what
# makes a generated case exact: the grader matches the plugin-qualified skill id the
# Skill tool records in the trace, so compound-capture firing does not satisfy a
# compound-retrieve case.
#
# verification-stack-eval.json is deliberately absent: its queries ("run pytest,
# ruff and mypy") describe a verification surface that no skill in this repo
# exposes. stick-shift ships /verify as a slash command, and a command never
# appears as a Skill call, so there is nothing here a trigger grader could assert.
FIXTURE_TARGET: dict[str, tuple[str, str]] = {
    "mochi-creator-eval": ("mochi-creator", "mochi-creator"),
    "compound-capture-eval": ("compound-knowledge", "compound-capture"),
    "compound-retrieve-eval": ("compound-knowledge", "compound-retrieve"),
    "hexagonal-agents-eval": ("hexagonal-agents", "hexagonal-agents"),
    "bdd-spec-eval": ("autonomous-sdlc", "bdd-spec"),
    "bdd-generate-eval": ("autonomous-sdlc", "bdd-generate"),
    "tdd-workflow-eval": ("autonomous-sdlc", "tdd-workflow"),
    "beads-workflow-eval": ("autonomous-sdlc", "beads-workflow"),
}

# Cases this script owns are marked so --check can tell them apart from
# hand-authored ones living in the same evals/ directory.
MARKER = "<!-- generated by scripts/gen_trigger_evals.py; edit the fixture, not this file -->"

PROMPT_TEMPLATE = """\
---
description: {description}
max_turns: {max_turns}
allowed_tools: [Read, Glob, Grep, Skill]
---
{query}

{marker}
"""

# The Skill tool records the plugin-qualified id ("mochi-creator:mochi-creator") in
# its input, so a trace regex pins the exact skill. `tool_used: Skill` would only say
# that *some* skill fired, which cannot separate compound-capture from
# compound-retrieve, or bdd-spec from tdd-workflow.
POSITIVE_GRADER = """\
---
type: regex
target: trace
pattern: {pattern}
match: contains
---
The {skill} skill claims this phrasing as a trigger, so it must load rather than the
model answering from its own priors.

{marker}
"""

NEGATIVE_GRADER = """\
---
type: regex
target: trace
pattern: {pattern}
match: not_contains
---
This request is outside {skill}'s remit. Loading it here means the description
over-triggers and would shadow whatever skill actually owns the request.

{marker}
"""


def case_dirs_for(plugin_dir: Path, fixture: str) -> list[Path]:
    """Every generated case directory belonging to ``fixture``, newest listing order."""
    evals = plugin_dir / "evals"
    if not evals.is_dir():
        return []
    return sorted(d for d in evals.iterdir() if d.is_dir() and d.name.startswith(f"{fixture}-"))


def render(fixture: str, cases: list[dict], limit: int) -> dict[Path, str]:
    """Return {relative path: file contents} for one fixture's generated cases."""
    plugin, skill = FIXTURE_TARGET[fixture]
    root = Path("plugins") / plugin / "evals"
    # Matches the Skill tool's own input in the trace, e.g.
    #   "skill":"compound-knowledge:compound-retrieve"
    # The `"skill":"` anchor keeps it off the skill listing in the system prompt,
    # where the same id appears as bare prose.
    pattern = json.dumps(f'"skill":"{plugin}:{skill}"')
    out: dict[Path, str] = {}

    for polarity, want in (("pos", True), ("neg", False)):
        selected = [c for c in cases if bool(c["should_trigger"]) is want][:limit]
        for index, case in enumerate(selected, start=1):
            name = f"{fixture}-{polarity}-{index:02d}"
            query = str(case["query"]).strip()
            verb = "must" if want else "must not"
            out[root / name / "prompt.md"] = PROMPT_TEMPLATE.format(
                description=json.dumps(f"Trigger fixture: a skill {verb} load for this request."),
                # Positive cases need room to load a skill and answer; negatives
                # only need enough turns to prove no skill fired.
                max_turns=10 if want else 6,
                query=query,
                marker=MARKER,
            )
            grader = POSITIVE_GRADER if want else NEGATIVE_GRADER
            out[root / name / "graders" / "trigger.md"] = grader.format(
                skill=skill, pattern=pattern, marker=MARKER
            )
    return out


def desired(fixtures: list[str], limit: int) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for fixture in fixtures:
        payload = json.loads((FIXTURES / f"{fixture}.json").read_text())
        out.update(render(fixture, payload, limit))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if generated cases are stale")
    mode.add_argument("--write", action="store_true", help="(re)generate the cases")
    parser.add_argument(
        "--limit",
        type=int,
        default=3,
        help="cases to emit per polarity per fixture (default 3; each costs an agent run per arm)",
    )
    parser.add_argument(
        "--fixture",
        action="append",
        help="only this fixture (repeatable); default is every fixture in evals/",
    )
    args = parser.parse_args()

    fixtures = args.fixture or sorted(FIXTURE_TARGET)
    unknown = [f for f in fixtures if f not in FIXTURE_TARGET]
    if unknown:
        print(f"unknown fixture(s): {', '.join(unknown)}", file=sys.stderr)
        print(f"known: {', '.join(sorted(FIXTURE_TARGET))}", file=sys.stderr)
        return 2

    if args.limit < 1:
        print("--limit must be at least 1", file=sys.stderr)
        return 2

    wanted = desired(fixtures, args.limit)

    if args.write:
        # Drop the previous generation first so a lowered --limit removes cases.
        for fixture in fixtures:
            for stale in case_dirs_for(REPO_ROOT / "plugins" / FIXTURE_TARGET[fixture][0], fixture):
                shutil.rmtree(stale)
        for relative, text in sorted(wanted.items()):
            target = REPO_ROOT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        cases = len({p.parent for p in wanted if p.name == "prompt.md"})
        print(f"wrote {cases} case(s) across {len(fixtures)} fixture(s)")
        return 0

    drift: list[str] = []
    for relative, text in sorted(wanted.items()):
        target = REPO_ROOT / relative
        if not target.exists():
            drift.append(f"missing: {relative}")
        elif target.read_text() != text:
            drift.append(f"stale:   {relative}")

    expected = {p.parent for p in wanted if p.name == "prompt.md"}
    for fixture in fixtures:
        for present in case_dirs_for(REPO_ROOT / "plugins" / FIXTURE_TARGET[fixture][0], fixture):
            if present.relative_to(REPO_ROOT) not in expected:
                drift.append(f"extra:   {present.relative_to(REPO_ROOT)}")

    if drift:
        print("generated trigger cases are out of date:", file=sys.stderr)
        for line in drift:
            print(f"  {line}", file=sys.stderr)
        print("\nrun: python scripts/gen_trigger_evals.py --write", file=sys.stderr)
        return 1

    print(f"generated trigger cases up to date ({len(expected)} case(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
